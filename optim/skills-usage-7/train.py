def log(msg: str) -> None:
    line = f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {msg}"
    with _log_lock:
        with open(TRAIN_LOG, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    print(line, flush=True)


