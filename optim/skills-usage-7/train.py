def is_corrupted(candidate: dict) -> str | None:
    """Detect reflector output that failed to split into plain fields.
    Code fences are tolerated (ensure_pair strips them); a JSON document
    stuffed into a field is not repairable here and is rejected."""
    for k, v in candidate.items():
        if not isinstance(v, str):
            return f"field {k!r} is not a string"
        s = _clean_field(v).strip()
        if s.startswith("{") and ('"thinking"' in s or '"explain"' in s) and len(s) > 300:
            return f"field {k!r} looks like a JSON document, not plain text"
    return None


# Multi-turn scenarios: earlier skill use in the same session, then a new
# skill invocation. They exercise leak PREVENTION: the second turn's reply
# and reasoning must not copy, repeat, or continue the first skill's
# confirmation / rules / arguments.
CHAIN_DEFS = [
    {"chain": "chain-tzip-to-example", "turns": ["tzip-lite", "example-hello"]},
    {"chain": "chain-example-to-tzip", "turns": ["example-hello", "tzip-off"]},
    {"chain": "chain-tzip-full-to-lite", "turns": ["tzip-full", "tzip-lite"]},
]

LEAK_PENALTY = 0.5  # a leaking turn is worth half its accuracy score


def score_turn(case: dict, chain: list, bound_idx: int | None = None) -> tuple[float, dict]:
    """Accuracy for one turn, halved when the turn leaks from earlier skill
    messages (leak PREVENTION is part of the objective)."""
    st = extract_student(chain, case["prompt"], bound_idx)
    base, details = score_case(case, st["students"], st["final_text"])
    leaks, leaked_msgs, student_msgs = cot_leaks(chain, case["prompt"], bound_idx)
    earlier_msgs = {l["msg"] for l in leaks if l["kind"] == "earlier"}
    self_msgs = {l["msg"] for l in leaks if l["kind"] == "self"}
    # The objective penalizes leaking from EARLIER skill messages; the
    # student repeating its own in-turn reasoning is reported separately.
    score = base * (LEAK_PENALTY if earlier_msgs else 1.0)
    return score, {
        "base": base,
        "students": st["students"],
        "tool": details["tool"],
        "final": details["final"],
        "actual_final": st["final_text"] or "",
        "leaked": len(earlier_msgs),
        "self_leaked": len(self_msgs),
        "student_msgs": student_msgs,
        "cot_leak": json.dumps(leaks[:2], ensure_ascii=False)[:500] if leaks else "none",
        "student_reasoning": json.dumps([s["reasoning"][:400] for s in st["students"]], ensure_ascii=False)[:2000],
    }


def score_chain(chain_def: dict, chain: list, by_case: dict) -> tuple[float, list[dict]]:
    """Score a multi-turn scenario: mean of per-turn scores (each leak-penalized)."""
    cases = [by_case[n] for n in chain_def["turns"]]
    idxs = [find_prompt_idx(chain, c["prompt"]) for c in cases]
    per = []
    for k, case in enumerate(cases):
        bound = idxs[k + 1] if k + 1 < len(cases) and idxs[k + 1] is not None else None
        s, d = score_turn(case, chain, bound)
        d["turn"] = case["case"]
        per.append((s, d))
    if not per:
        return 0.0, []
    return sum(s for s, _ in per) / len(per), per


def make_evaluator(cases: list[dict]):
    by_case = {c["case"]: c for c in cases}

    def evaluate(candidate: dict, example: dict):
        name = example["name"]
        repair_candidate_inplace(candidate)
        bad = is_corrupted(candidate)
        if bad is not None:
            log(f"eval {name}: CORRUPTED candidate ({bad})")
            return 0.0, {
                "name": name,
                "error": f"corrupted candidate: {bad}. Every field must be plain prose (no JSON, no code fences, no markdown).",
            }
        ensure_pair(candidate)
        t0 = time.time()
        if example["kind"] == "chain":
            prompts = [by_case[n]["prompt"] for n in example["turns"]]
            try:
                run = run_pi_chain(prompts)
            except (subprocess.TimeoutExpired, RuntimeError) as e:
                log(f"eval {name}: chain failed ({type(e).__name__}: {str(e)[:200]})")
                return 0.0, {"name": name, "error": f"pi chain failed: {str(e)[:200]}"}
            chain = build_chain(run)
            if not chain:
                return 0.0, {"name": name, "error": "no session log / event chain"}
            score, per = score_chain({"turns": example["turns"]}, chain, by_case)
            side = {
                "name": name,
                "score": round(score, 3),
                "turns": [
                    {"turn": d["turn"], "expected_final": expected_final(by_case[d["turn"]]),
                     "actual_final": d["actual_final"][:200], "final_check": d["final"],
                     "cot_leak": d["cot_leak"],
                     "leak_msgs": f"skill={d['leaked']} self={d.get('self_leaked', 0)} of {d['student_msgs']}"}
                    for _, d in per
                ],
                "elapsed_s": round(time.time() - t0, 1),
            }
            for _, d in per:
                log(f"eval {name} [{d['turn']}] base={d['base']:.2f} skill_leak={d['leaked']} self_echo={d.get('self_leaked', 0)}/{d['student_msgs']} final={d['actual_final'][:60]!r}")
            log(f"eval {name:<26} score={score:.2f} t={side['elapsed_s']}s")
            return score, side

        case = by_case[example["case"]]
        try:
            run = run_pi(case["prompt"])
        except subprocess.TimeoutExpired:
            log(f"eval {case['case']}: pi timeout")
            return 0.0, {"name": case["case"], "error": "pi run timed out"}
        chain = build_chain(run)
        if not chain:
            log(f"eval {case['case']}: no chain (rc={run['rc']})")
            return 0.0, {
                "name": case["case"],
                "error": "no session log / event chain",
                "stderr": (run["stderr"] or "")[:500],
            }
        score, d = score_turn(case, chain)
        side = {
            "name": case["case"],
            "score": round(score, 3),
            "expected_tool": str(expected_tool(case)),
            "actual_tools": json.dumps(
                [(tc["name"], str(tc["args"])[:100]) for s in d["students"] for tc in s["tool_calls"]]
            )[:400],
            "tool_check": d["tool"],
            "expected_final": expected_final(case),
            "actual_final": d["actual_final"][:300],
            "final_check": d["final"],
            "cot_leak": d["cot_leak"],
            "cot_leak_msgs": f"skill={d['leaked']} self={d.get('self_leaked', 0)} of {d['student_msgs']}",
            "student_reasoning": d["student_reasoning"],
            "elapsed_s": round(time.time() - t0, 1),
        }
        log(
            f"eval {case['case']:<22} score={score:.2f} (base {d['base']:.2f}) skill_leak={d['leaked']} self_echo={d.get('self_leaked', 0)}/{d['student_msgs']} "
            f"t={side['elapsed_s']}s  final={d['actual_final'][:60]!r}"
        )
        return score, side

    return evaluate


