"""train.py — optimize the slm.ts "skill-system" pair with GEPA.

Pipeline
--------
1. The pi extension `slm.ts` injects a simulated dialogue at the start of
   every session. The LAST pair (user ask + synthetic assistant reply with
   `reasoning_content`) is overridden by the companion extension
   `pair-override.ts` (loaded after slm.ts) from the single file
   `skill-pair.json` next to it. slm.ts itself is never edited.
2. For every evaluation case in `expected-responses/` a fresh
   `pi -p --mode json ...` process is spawned (student model
   LiquidAI/LFM2.5-2.6B, thinking high). The student receives one `<skill>`
   block (+ bare argument) as its user message.
3. Observation channels (both automated here):
   - the JSON event stream (final assistant message, tool calls);
   - the session log `.pi/pi-llm-debugging/<session_id>/NNN-req.json`
     (the latest *-req.json is the most complete context snapshot).
4. Scoring per case:
   - tool-call correctness (name + arguments, e.g. read path / bash script
     path + args);
   - final-reply correctness vs expected-responses (exact line for tzip,
     exact fixed reply / script output report for the example skill);
   - CoT leak: the student's reasoning_content in a later chain message
     must not verbatim-copy (>=8 consecutive words) an earlier assistant
     message's reasoning or answer.
5. GEPA (`gepa.optimize_anything`) evolves the pair
   {"ask", "explain", "thinking"}; the reflection LM is the teacher
   Qwen/Qwen3.8-27B with thinking OFF. The seed `thinking` is generated by
   the teacher in the student's voice per REASONING-LiquidAI-LFM2.5-2.6B.md.
6. All GEPA/dspy intermediate files live under `runs/`; progress is appended
   to `./train.log`.

Usage
-----
    venv/bin/python train.py baseline                 # score current pair
    venv/bin/python train.py optimize                 # run GEPA (resumable)
    venv/bin/python train.py optimize --run-dir runs/gepa-xxx
    venv/bin/python train.py eval --pair path.json    # score an arbitrary pair
"""

