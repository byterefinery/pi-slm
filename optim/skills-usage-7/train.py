def _models() -> dict:
    raw = MODELS_JSON.read_text()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        # pi's models.json may carry trailing commas; strip them and retry
        return json.loads(re.sub(r",(\s*[}\]])", r"\1", raw))


def _sampling(model_id: str) -> dict:
    prov = _models()["providers"][PROVIDER]
    for m in prov.get("models", []):
        if m.get("id") == model_id:
            return m.get("samplingParams", {}) or {}
    return {}


def _endpoints() -> tuple[str, str]:
    prov = _models()["providers"][PROVIDER]
    return prov["baseUrl"], prov["apiKey"]


def teacher_lm() -> dspy.LM:
    """Teacher: Qwen/Qwen3.8-27B, thinking OFF (enable_thinking=false)."""
    api_base, api_key = _endpoints()
    s = _sampling(TEACHER_MODEL)
    extra_body = {
        k: s[k]
        for k in ("top_k", "min_p", "presence_penalty", "repeat_penalty", "top_p")
        if k in s
    }
    extra_body["chat_template_kwargs"] = {
        "enable_thinking": False,
        "preserve_thinking": True,
    }
    return dspy.LM(
        f"openai/{TEACHER_MODEL}",
        api_base=api_base,
        api_key=api_key,
        model_type="chat",
        temperature=s.get("temperature", 1.0),
        max_tokens=16384,
        cache=False,
        num_retries=5,
        extra_headers={"x-session-affinity": f"dspy-optim-lfm2.5-2.6b-{RUN_ID}"},
        extra_body=extra_body,
    )


def make_teacher_complete(lm: dspy.LM):
    """Wrap the teacher LM into a callable returning str (GEPA reflection_lm)."""

    def complete(prompt: str) -> str:
        out = lm(prompt, temperature=0.7)
        if isinstance(out, list):
            return out[0]
        return out

    return complete


def generate_seed_thinking(lm: dspy.LM, ask: str, explain: str) -> str:
    """Teacher (thinking off) writes the synthetic reasoning_content: a
    structured, true chain of thought in the student's voice, following
    REASONING-LiquidAI-LFM2.5-2.6B.md."""
    doc = REASONING_DOC.read_text()
    prompt = f"""{doc}

TASK: You are writing the reasoning_content (the model's private inner
monologue) of one specific assistant message in a pi coding session.

The user message it answers is:
"{ask}"

The assistant's visible reply (already fixed, do not change or repeat it):
"{explain}"

Write ONLY the reasoning_content. Requirements:
- A true chain of thought of 4-8 plain sentences (~400-700 characters), in the
  student model's voice, with the 5-part shape from the guide above:
  1. open by naming the situation in the first person ("The user asks ...");
  2. a short numbered plan (plain "1. ... 2. ..." sentences) for executing ANY
     <skill> block generically: locate the current block, read its name, Usage
     rules and the bare argument after its closing tag, then pick the Usage
     branch matching the argument — a fixed reply to send exactly, a reference
     file to load with the read tool and follow, or a script to run with bash
     passing the argument as CLI parameters and report its output;
  3. an isolation step: if an earlier message contains another skill block or a
     short confirmation line, that task is finished — its words are not this
     argument, and nothing from it may enter this reply or this reasoning;
  4. a self-check / close committing to the exact action the visible reply
     performs: perform the current block's required behavior exactly, never
     explain the skill, never ask, never repeat an earlier confirmation;
  5. a brief paraphrase note: I state the plan in my own words each time and
     never copy these instructions or any earlier message verbatim.
- Skill-agnostic: it must cover simple skills, skills with reference files, and
  skills with scripts, without naming any specific skill.
- Plain prose only: NO markdown (no #, no **, no backticks, no dash bullets),
  no headers. Numbered "1. ..." plan sentences are fine.
- No meta talk (never mention being synthetic or the reasoning itself).
- Anti-echo (IMPORTANT): the user message above already contains a plan
  paragraph. Do NOT reuse any of its sentences or clause order. Express the
  same plan with different, varied wording and a different order where sensible.
- The paraphrase note and the closing marker from the guide (for example
  "Now final output.") must both be present.
- Output the reasoning text only, nothing else."""
    out = lm(prompt, temperature=0.7)
    text = out[0] if isinstance(out, list) else out
    return _clean_field(text)


