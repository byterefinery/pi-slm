def load_pair(path: Path = PAIR_FILE) -> dict:
    data = json.loads(path.read_text())
    return {k: data[k] for k in PAIR_KEYS if isinstance(data.get(k), str)}


def write_pair(candidate: dict, path: Path = PAIR_FILE) -> None:
    path.write_text(
        json.dumps({k: candidate[k] for k in PAIR_KEYS}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


_pair_lock = threading.Lock()
_last_pair_hash: str | None = None


def _clean_field(v: str) -> str:
    """Strip reflector artifacts: wrapping code fences and quote marks."""
    s = (v or "").strip()
    if s.startswith("```"):
        s = s.split("\n", 1)[1] if "\n" in s else s[3:]
        if s.rstrip().endswith("```"):
            s = s.rstrip()[:-3]
        s = s.strip()
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        s = s[1:-1].strip()
    return s


def repair_candidate_inplace(candidate: dict) -> None:
    """Fix reflector output where a whole JSON document got stuffed into a
    field: recover each field's value from the embedded JSON, in place (so
    GEPA's population sees the repaired candidate too)."""
    for k in PAIR_KEYS:
        v = candidate.get(k, "")
        s = (v or "").strip()
        if not (s.startswith("{") and len(s) > 300):
            continue
        try:
            doc, _ = json.JSONDecoder().raw_decode(s[s.index("{"):])
        except json.JSONDecodeError:
            continue
        containers = [doc] + [x for x in doc.values() if isinstance(x, dict)]
        for cont in containers:
            cand = cont.get(k)
            if isinstance(cand, str) and len(cand.strip()) >= 30:
                candidate[k] = _clean_field(cand)
                break


def ensure_pair(candidate: dict) -> None:
    """Write skill-pair.json (sanitized) only when the candidate changes."""
    global _last_pair_hash
    clean = {k: _clean_field(candidate.get(k, "")) for k in PAIR_KEYS}
    content = json.dumps(clean, ensure_ascii=False, indent=2)
    h = hashlib.sha256(content.encode("utf-8")).hexdigest()
    with _pair_lock:
        if h == _last_pair_hash:
            return
        PAIR_FILE.write_text(content + "\n", encoding="utf-8")
        _last_pair_hash = h
        log(
            f"pair file updated hash={h[:10]} "
            f"(ask={len(clean['ask'])}c explain={len(clean['explain'])}c thinking={len(clean['thinking'])}c)"
        )


