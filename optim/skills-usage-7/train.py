def eval_single(candidate: dict, case: dict) -> tuple[float, dict]:
    t0 = time.time()
    try:
        run = run_pi(case["prompt"])
    except subprocess.TimeoutExpired:
        log(f"eval {case['case']}: pi timeout")
        return 0.0, {"error": "timeout", "actual_final": "", "leaked": 0, "self_leaked": 0, "student_msgs": 0}
    chain = build_chain(run)
    if not chain:
        return 0.0, {"error": "no chain", "actual_final": "", "leaked": 0, "self_leaked": 0, "student_msgs": 0}
    score, d = score_turn(case, chain)
    log(
        f"eval {case['case']:<22} score={score:.2f} (base {d['base']:.2f}) skill_leak={d['leaked']} self_echo={d.get('self_leaked', 0)}/{d['student_msgs']} "
        f"t={time.time()-t0:.0f}s final={d['actual_final'][:60]!r}"
    )
    return score, d


def eval_chain(candidate: dict, chain_def: dict, by_case: dict) -> tuple[float, dict]:
    name = chain_def["chain"]
    prompts = [by_case[n]["prompt"] for n in chain_def["turns"]]
    t0 = time.time()
    try:
        run = run_pi_chain(prompts)
    except (subprocess.TimeoutExpired, RuntimeError) as e:
        log(f"eval {name}: chain failed ({type(e).__name__}: {str(e)[:200]})")
        return 0.0, {"error": str(e)[:200], "actual_final": "", "leaked": 0, "self_leaked": 0, "student_msgs": 0}
    chain = build_chain(run)
    if not chain:
        return 0.0, {"error": "no chain", "actual_final": "", "leaked": 0, "self_leaked": 0, "student_msgs": 0}
    score, per = score_chain(chain_def, chain, by_case)
    leaked = sum(d["leaked"] for _, d in per)
    self_leaked = sum(d.get("self_leaked", 0) for _, d in per)
    n_msgs = sum(d["student_msgs"] for _, d in per)
    log(
        f"eval {name:<26} score={score:.2f} skill_leak={leaked} self_echo={self_leaked}/{n_msgs} t={time.time()-t0:.0f}s "
        + " | ".join(f"[{d['turn']}] {d['actual_final'][:50]!r}" for _, d in per)
    )
    return score, {"actual_final": "", "leaked": leaked, "self_leaked": self_leaked, "student_msgs": n_msgs,
                   "turns": [{"turn": d["turn"], "score": s, **{k: v for k, v in d.items() if k != "turn"}} for s, d in per]}


def evaluate_pair(candidate: dict, cases: list[dict], label: str) -> dict:
    """Full report: all 12 single cases + all 3 multi-turn chains."""
    by_case = {c["case"]: c for c in cases}
    log(f"=== evaluating pair ({label}) on {len(cases)} cases + {len(CHAIN_DEFS)} chains ===")
    ensure_pair(candidate)
    rows = []
    total = 0.0
    n_items = len(cases) + len(CHAIN_DEFS)
    leaked = 0
    self_leaked = 0
    student_msgs = 0
    for case in cases:
        score, details = eval_single(candidate, case)
        total += score
        leaked += details.get("leaked", 0)
        self_leaked += details.get("self_leaked", 0)
        student_msgs += details.get("student_msgs", 0)
        rows.append({"case": case["case"], "score": score, **details})
    for cd in CHAIN_DEFS:
        score, details = eval_chain(candidate, cd, by_case)
        total += score
        leaked += details.get("leaked", 0)
        self_leaked += details.get("self_leaked", 0)
        student_msgs += details.get("student_msgs", 0)
        rows.append({"case": cd["chain"], "score": score, **details})
    acc = 100.0 * total / n_items
    skill_leak_rate = 100.0 * leaked / student_msgs if student_msgs else 0.0
    self_echo_rate = 100.0 * self_leaked / student_msgs if student_msgs else 0.0
    result = {
        "label": label,
        "pair": candidate,
        "accuracy_pct": round(acc, 2),
        "skill_leak_pct": round(skill_leak_rate, 2),
        "skill_leak_detail": f"{leaked}/{student_msgs} student reasoning messages copied an EARLIER skill message",
        "self_echo_pct": round(self_echo_rate, 2),
        "self_echo_detail": f"{self_leaked}/{student_msgs} student reasoning messages repeated the student's own earlier reasoning",
        "cases": rows,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    log(
        f"=== RESULT ({label}) accuracy={acc:.2f}%  skill-message leak={skill_leak_rate:.2f}% "
        f"({leaked}/{student_msgs} msgs)  self-echo={self_echo_rate:.2f}% ({self_leaked}/{student_msgs}) ==="
    )
    for r in rows:
        mark = "OK " if r["score"] >= 1.0 else "PART" if r["score"] > 0 else "FAIL"
        log(f"   {mark} {r['case']:<26} {r['score']:.2f}  skill_leak={r.get('leaked',0)} self_echo={r.get('self_leaked',0)}/{r.get('student_msgs',0)}  final={r.get('actual_final','')[:70]!r}")
    return result


