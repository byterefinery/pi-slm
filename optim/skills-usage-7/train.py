OBJECTIVE = """Make a small student language model (2.6B params) EXECUTE <skill> blocks correctly,
right after seeing the synthetic skill-system pair (the component being optimized:
fields "ask", "explain", "thinking") at the start of the session.

Required behaviors when the next user message contains one <skill> block (optionally
followed by a bare argument after the closing tag):

1. tzip skill — reply with EXACTLY the one-line confirmation and nothing else
   (no bold, no explanation, no extra lines):
   - no argument, "on" or "lite"  ->  tzip lite activated
   - "full"  ->  tzip full activated
   - "ultra" ->  tzip ultra activated
   - "off"   ->  tzip deactivated
2. webfetch skill —
   - bare URL, no other request -> run exactly one bash command: the skill
     dir's scripts/webfetch.sh with the URL (no flags, no cd), using the path
     built from the header's skill directory, then report the fetched content
     from the bash result. Never read the script files, never run webfetch.py.
3. example skill —
   - no extra text      ->  reply exactly: This is an example skill.
   - argument "Hello" (exact case) ->  call the read tool on
     <skill-dir>/references/03-hello.md, then reply exactly: world
   - any other text (including case variants like "hello", or "call script", or
     words like "Hi"/"Bye") ->  call the bash tool running
     <skill-dir>/scripts/example.sh with the text as CLI parameters, then report
     the script output in the reply.
4. The skill dir <skill-dir> is the directory named in the block's `location`
   attribute (the folder containing SKILL.md). Reference files and scripts live
   under it, relative to it.

The student must never explain what a skill is, never ask questions, and never
call read on SKILL.md itself. Argument matching is case-sensitive: only the exact
word "Hello" triggers the reference-file read.

Multi-turn: in later turns the context also contains EARLIER <skill> blocks and
their confirmations (e.g. a short line like a mode confirmation). Those tasks
are finished. The reply to the CURRENT block must not copy, repeat, or continue
an earlier skill's reply or confirmation, must not use an earlier argument, and
the student's reasoning must not import earlier skill messages (skill-message
CoT leak). A turn whose reply or reasoning copies an earlier skill message is
scored at half value. The student re-anchoring on its OWN earlier reasoning
within the same turn (self-echo) is reported separately and is not penalized.
Keep skill-message leak at zero."""

BACKGROUND = """Mechanics:
- The pair is injected by a pi extension as a simulated dialogue at the very start
  of every session: the user message is "ask"; the assistant message is "explain"
  and its reasoning_content is "thinking". This pair sits immediately before the
  real user message (the <skill> block). The student sees "thinking" as the
  assistant's reasoning — it is the strongest behavioral signal for what the
  student does next.
- The student is LiquidAI/LFM2.5-2.6B with thinking ON. It imitates: whatever the
  synthetic reasoning commits to is what the student tends to do.

Student failure modes to fix (observed):
(1) treating the <skill> block as a question and explaining the skill instead of
    executing it;
(2) calling read on SKILL.md before acting;
(3) wrapping the required reply in bold/markdown or adding explanation lines;
(4) CoT leak: copying the previous messages' reasoning or confirmations verbatim
    into its own reasoning — each <skill> block is a fresh, independent
    invocation; nothing may be imported from earlier messages.

Constraints on the component (hard requirements):
- Both "explain" and "thinking" are PLAIN PROSE: no markdown at all (no #,
  no **, no backticks, no dash bullets, no code fences, no tables).
- "explain": directly explains how a skill is USED, skill-agnostic, 3-6 short
  sentences, first person. It must say: a <skill> block is a task to execute
  (never a question to answer); read the block's name, its Usage rules, and the
  bare argument after the current block's closing tag; then do exactly what the
  block's Usage says for that argument — send a required fixed reply exactly,
  or load the named reference file with the read tool and follow it, or run the
  named script with bash passing the argument as CLI parameters and report the
  output; paths come from the block's location attribute; the reply contains
  only what the block requires; and it must state the isolation rule: earlier
  messages may contain other skill blocks or their short confirmations, those
  tasks are finished, ignore them completely, never copy/repeat/continue an
  earlier skill's reply, never use an earlier argument, derive everything from
  the current block only.
- "thinking": a true, structured chain of thought in the student model's voice
  (first person, simple words, no meta talk), 4-8 plain sentences (~400-700
  characters), shaped as: (1) name the situation ("The user asks ...");
  (2) a short numbered plan ("1. ... 2. ...") for executing ANY skill block
  generically (locate block, read Usage + argument after the closing tag, pick
  the matching Usage branch: fixed reply / reference file / script);
  (3) an isolation step: if an earlier message contains another skill block or
  a short confirmation line, that task is finished — its words are not this
  argument, and nothing from it may enter this reply or this reasoning;
  (4) close by committing to the exact action the visible reply performs:
  execute the current block's required behavior, never explain the skill,
  never ask, never repeat an earlier confirmation;
  (5) a brief paraphrase note that the plan is stated in my own words each
  time, never copied verbatim from these instructions or any earlier message.
  It must be skill-agnostic (simple skills, skills with reference files, skills
  with scripts) and must not name any specific skill.
- Do not invent rules that contradict the skills' own Usage sections. Keep all
  three fields; do not change field names.

Evaluator evidence in <side_info>: per-case (and per-turn for multi-turn
chains) score, expected vs actual tool call, expected vs actual final reply,
and leak evidence: skill-message leaks (verbatim overlap of the student's
reasoning with an EARLIER skill message — an earlier assistant message or an
earlier user skill block) are penalized at half value, while self-echo
(overlap with the student's own earlier reasoning in the same turn) is reported
separately. Maximize total score; keep skill-message leak at zero."""


# Small core subset covering the three skill branches (fixed reply via
# "example-empty" is excluded to keep the loop cheap; final validation always
# runs the full set). Core: confirmation line, deactivation, reference-file
# branch, script branch — plus the multi-turn leak chains.
CORE_CASES = ("tzip-lite", "tzip-off", "tzip-full", "example-hello", "example-hi", "webfetch-plain")


def build_examples(cases: list[dict], all_cases: bool) -> list[dict]:
    """GEPA dataset: single cases (core 4 or all 12) + the multi-turn chains."""
    ex = []
    core = cases if all_cases else [c for c in cases if c["case"] in CORE_CASES]
    for c in core:
        ex.append({"kind": "case", "name": c["case"], "case": c["case"], "prompt": c["prompt"]})
    for cd in CHAIN_DEFS:
        ex.append({"kind": "chain", "name": cd["chain"], "turns": cd["turns"]})
    return ex


def run_gepa(args) -> None:
    from gepa.optimize_anything import (
        EngineConfig,
        GEPAConfig,
        MergeConfig,
        ReflectionConfig,
        optimize_anything,
    )

    cases = load_cases()
    examples = build_examples(cases, args.all_cases)
    run_dir = Path(args.run_dir) if args.run_dir else RUNS_DIR / f"gepa-{RUN_ID}"
    run_dir.mkdir(parents=True, exist_ok=True)

    seed = load_pair(Path(args.seed_pair))
    if args.regenerate_thinking:
        log("generating seed 'thinking' with teacher (thinking off)...")
        seed["thinking"] = generate_seed_thinking(teacher_lm(), seed["ask"], seed["explain"])
        log(f"seed thinking: {seed['thinking'][:200]!r}")
    else:
        log(f"seed pair: explain={seed['explain'][:100]!r}... thinking={seed['thinking'][:100]!r}...")

    # baseline before optimizing
    baseline = evaluate_pair(seed, cases, "seed-baseline")
    (run_dir / "seed-baseline.json").write_text(json.dumps(baseline, indent=2))

    teacher = teacher_lm()
    evaluator = make_evaluator(cases)
    log(
        f"starting GEPA: run_dir={run_dir} max_metric_calls={args.max_calls} "
        f"optimization examples={len(examples)} (full eval set={len(cases)} cases + {len(CHAIN_DEFS)} chains) "
        f"reflection_lm={TEACHER_MODEL} (thinking off, callable wrapper)"
    )

    result = optimize_anything(
        seed_candidate=seed,
        evaluator=evaluator,
        dataset=examples,
        objective=OBJECTIVE,
        background=BACKGROUND,
        config=GEPAConfig(
            engine=EngineConfig(
                run_dir=str(run_dir),
                max_metric_calls=args.max_calls,
                parallel=False,
                raise_on_exception=False,
                use_cloudpickle=False,
                track_best_outputs=True,
            ),
            reflection=ReflectionConfig(
                reflection_lm=make_teacher_complete(teacher),
                reflection_minibatch_size=3,
                # one plain-text component per reflection (avoids the
                # reflector emitting the whole JSON dict and corrupting fields)
                module_selector="round_robin",
            ),
            merge=MergeConfig(max_merge_invocations=5),
        ),
    )

    best = result.best_candidate
    best = {k: best.get(k, seed.get(k, "")) for k in PAIR_KEYS}
    log(f"GEPA done. best_idx={result.best_idx} total_metric_calls={result.total_metric_calls}")
    log(f"BEST pair:\nask={best['ask']}\nexplain={best['explain']}\nthinking={best['thinking']}")

    # persist best candidate + activate it as the live pair
    (run_dir / "best-pair.json").write_text(json.dumps(best, ensure_ascii=False, indent=2))
    write_pair(best)
    log("best pair written to skill-pair.json (now live for slm.ts)")

    # final validation of the best candidate
    final = evaluate_pair(best, cases, "best-final")
    (run_dir / "best-final.json").write_text(json.dumps(final, indent=2))

    summary = {
        "run_dir": str(run_dir),
        "best_idx": result.best_idx,
        "total_metric_calls": result.total_metric_calls,
        "best_candidate": best,
        "seed_baseline": {
            "accuracy_pct": baseline["accuracy_pct"],
            "skill_leak_pct": baseline["skill_leak_pct"],
            "self_echo_pct": baseline["self_echo_pct"],
        },
        "best_final": {
            "accuracy_pct": final["accuracy_pct"],
            "skill_leak_pct": final["skill_leak_pct"],
            "self_echo_pct": final["self_echo_pct"],
        },
    }
    (run_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2))
    log(
        f"SUMMARY: accuracy {baseline['accuracy_pct']}% -> {final['accuracy_pct']}%, "
        f"skill-leak {baseline['skill_leak_pct']}% -> {final['skill_leak_pct']}%, "
        f"self-echo {baseline['self_echo_pct']}% -> {final['self_echo_pct']}%"
    )


