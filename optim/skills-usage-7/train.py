def run_pi(prompt: str, timeout: int = 90, retries: int = 1) -> dict:
    """Run one single-shot pi eval. Correct answers complete in seconds, so a
    timeout means the student spiralled; retry once before scoring 0 (spirals
    are partly stochastic and re-runs of the same case often succeed)."""
    last_exc: Exception | None = None
    for attempt in range(1 + max(0, retries)):
        try:
            p = subprocess.run(
                PI_CMD + [prompt],
                cwd=str(HERE),
                capture_output=True,
                text=True,
                timeout=timeout,
            )
            break
        except subprocess.TimeoutExpired as e:
            last_exc = e
            if attempt < retries:
                log(f"run_pi timeout (attempt {attempt + 1}), retrying")
                continue
            raise
    events: list[dict] = []
    session_id: str | None = None
    for line in p.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            e = json.loads(line)
        except json.JSONDecodeError:
            continue
        events.append(e)
        if session_id is None and e.get("type") == "session":
            session_id = e.get("id")
    return {"rc": p.returncode, "events": events, "session_id": session_id, "stderr": p.stderr}


PI_CMD_RPC = [
    "pi",
    "--mode", "rpc",
    "--no-session",
    "--model", f"{PROVIDER}/{STUDENT_MODEL}",
    "--thinking", "high",
    "--no-tools", "--tools", "read,write,edit,bash",
    "--no-skills",
    "--skill", "../../.agents/skills-byterefinery/example/",
    "--skill", "../../.agents/skills-byterefinery/tzip/",
    "--skill", "../../.agents/skills/webfetch",
    "--skill", "../../.agents/skills/websearch",
    "-e", "slm.ts",
    "-e", "pair-override.ts",
]


def run_pi_chain(prompts: list[str], timeout: int = 300, retries: int = 1) -> dict:
    """Multi-turn session over the RPC protocol (one pi process).

    Sends each prompt as a `prompt` command and waits for the matching
    `agent_end` event before sending the next one. Retries the whole chain
    once on timeout (spirals are partly stochastic).
    """
    last_exc: Exception | None = None
    for attempt in range(1 + max(0, retries)):
        try:
            return _run_pi_chain_once(prompts, timeout)
        except (subprocess.TimeoutExpired, RuntimeError) as e:
            last_exc = e
            if attempt < retries:
                log(f"run_pi_chain failed ({type(e).__name__}, attempt {attempt + 1}), retrying")
                continue
            raise
    raise last_exc  # pragma: no cover


def _run_pi_chain_once(prompts: list[str], timeout: int) -> dict:
    """Single attempt of run_pi_chain."""
    debug_root = HERE / ".pi" / "pi-llm-debugging"
    _debug_before: set[str] = set()
    t_start = time.time()
    try:
        _debug_before = {d.name for d in debug_root.iterdir() if d.is_dir()}
    except FileNotFoundError:
        pass
    proc = subprocess.Popen(
        PI_CMD_RPC,
        cwd=str(HERE),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        bufsize=1,
    )
    events: list[dict] = []
    turns: list[dict] = []
    t_end = time.time() + timeout

    def new_debug_dirs() -> list[Path]:
        try:
            return [
                d
                for d in debug_root.iterdir()
                if d.is_dir() and d.name not in _debug_before and d.stat().st_mtime >= t_start - 5
            ]
        except FileNotFoundError:
            return []

    def readline() -> str:
        while True:
            if time.time() > t_end:
                raise subprocess.TimeoutExpired(PI_CMD_RPC, timeout)
            r, _, _ = select.select([proc.stdout], [], [], 0.5)
            if r:
                line = proc.stdout.readline()
                if not line:
                    err = (proc.stderr.read() or "")[:300]
                    raise RuntimeError(f"pi rpc closed stdout: {err}")
                line = line.strip()
                if line:
                    return line
            if proc.poll() is not None:
                err = (proc.stderr.read() or "")[:300]
                raise RuntimeError(f"pi rpc exited early: {err}")

    try:
        for i, p in enumerate(prompts):
            cmd = {"id": f"req-{i}", "type": "prompt", "message": p}
            proc.stdin.write(json.dumps(cmd, ensure_ascii=False) + "\n")
            proc.stdin.flush()
            resp = None
            while resp is None:
                e = json.loads(readline())
                events.append(e)
                if e.get("type") == "response" and e.get("id") == f"req-{i}":
                    resp = e
            if not resp.get("success"):
                raise RuntimeError(f"prompt {i} rejected: {resp}")
            while True:
                e = json.loads(readline())
                events.append(e)
                if e.get("type") == "agent_end":
                    turns.append(e)
                    break
    finally:
        try:
            proc.stdin.close()
        except Exception:
            pass
        proc.terminate()
        try:
            proc.wait(timeout=5)
        except Exception:
            proc.kill()
    # RPC emits no session header: find the session via the pi-llm-debugging
    # directory this run created (fallback: a session event, if any).
    session_id = None
    new_dirs = new_debug_dirs()
    if new_dirs:
        session_id = max(new_dirs, key=lambda d: d.stat().st_mtime).name
    for e in events:
        if e.get("type") == "session" and e.get("id"):
            session_id = e.get("id")
            break
    return {"events": events, "session_id": session_id, "turns": turns}


def read_latest_chain(session_id: str) -> list | None:
    """Latest *-req.json of the session: most complete context snapshot."""
    d = HERE / ".pi" / "pi-llm-debugging" / session_id
    if not d.is_dir():
        return None
    reqs = sorted(d.glob("*-req.json"))
    if not reqs:
        return None
    try:
        data = json.loads(reqs[-1].read_text())
        return data.get("messages", [])
    except Exception:
        return None


def events_final_chain(events: list[dict]) -> list | None:
    """Full in-memory message list from the agent_end event (includes the
    final assistant message that no *-req.json contains)."""
    for e in reversed(events):
        if e.get("type") == "agent_end":
            msgs = e.get("messages")
            if msgs:
                return msgs
    return None


def user_text(m: dict) -> str:
    c = m.get("content")
    if isinstance(c, str):
        return c
    if isinstance(c, list):
        return " ".join(b.get("text", "") for b in c if isinstance(b, dict) and b.get("type") == "text")
    return ""


def wire_assistant_from_event(m: dict) -> dict:
    content = m.get("content")
    content = content if isinstance(content, list) else []
    text = next((b.get("text") for b in content if b.get("type") == "text"), None)
    think = next((b.get("thinking") for b in content if b.get("type") == "thinking"), None)
    calls = [
        {"function": {"name": b.get("name"), "arguments": b.get("arguments")}}
        for b in content
        if b.get("type") == "toolCall"
    ]
    return {
        "role": "assistant",
        "content": text,
        "reasoning_content": think or "",
        "tool_calls": calls,
    }


def build_chain(run: dict) -> list | None:
    """Chain = latest request log + the final assistant message (events)."""
    chain = read_latest_chain(run["session_id"]) if run.get("session_id") else None
    ev = events_final_chain(run["events"])
    if not ev:
        return chain
    final = None
    for m in reversed(ev):
        if isinstance(m, dict) and m.get("role") == "assistant":
            final = wire_assistant_from_event(m)
            break
    if final is None:
        return chain
    if chain is None:
        return [final]
    # if the last logged message already equals the final one, do not duplicate
    last = chain[-1] if isinstance(chain[-1], dict) else {}
    if last.get("role") == "assistant" and last.get("reasoning_content") == final.get("reasoning_content") \
            and last.get("content") == final.get("content"):
        return chain
    return chain + [final]


def find_prompt_idx(chain: list, prompt: str) -> int | None:
    idx = None
    for i, m in enumerate(chain):
        if isinstance(m, dict) and m.get("role") == "user" and prompt in user_text(m):
            idx = i
    return idx


def extract_student(chain: list, prompt: str, bound_idx: int | None = None) -> dict:
    """Student-generated messages = assistant messages after the real user
    prompt (the <skill> block), before bound_idx when given."""
    idx = find_prompt_idx(chain, prompt)
    if idx is None:
        return {"students": [], "final_text": None}
    end = bound_idx if bound_idx is not None else len(chain)
    msgs = chain[idx + 1 : end]
    students = []
    for m in msgs:
        if not isinstance(m, dict) or m.get("role") != "assistant":
            continue
        tcs = []
        for tc in m.get("tool_calls") or []:
            fn = tc.get("function", {})
            args = fn.get("arguments")
            if isinstance(args, str):
                try:
                    args = json.loads(args)
                except json.JSONDecodeError:
                    pass
            tcs.append({"name": fn.get("name"), "args": args})
        text = m.get("content")
        students.append(
            {
                "text": text if isinstance(text, str) else None,
                "reasoning": m.get("reasoning_content") or "",
                "tool_calls": tcs,
            }
        )
    final = next((s["text"] for s in reversed(students) if s["text"]), None)
    return {"students": students, "final_text": final}


