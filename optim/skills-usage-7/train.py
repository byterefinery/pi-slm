# CoT leak detection
# --------------------------------------------------------------------------

PATH_RE = re.compile(r"(?:[A-Za-z0-9_.~*-]+/)+[A-Za-z0-9_.~*-]+")


def strip_paths(s: str) -> str:
    """Remove filesystem paths before leak comparison: quoting the task's
    own location path is data, not a CoT leak."""
    return PATH_RE.sub(" ", s or "")


def words(s: str | None) -> list[str]:
    return re.findall(r"[a-z0-9']+", (s or "").lower())


def longest_common_word_seq(a: str, b: str) -> tuple[int, str]:
    a_w, b_w = words(a), words(b)
    if not a_w or not b_w:
        return 0, ""
    n, m = len(a_w), len(b_w)
    best = 0
    best_end = 0
    prev = [0] * (m + 1)
    for i in range(1, n + 1):
        cur = [0] * (m + 1)
        aw = a_w[i - 1]
        for j in range(1, m + 1):
            if aw == b_w[j - 1]:
                cur[j] = prev[j - 1] + 1
                if cur[j] > best:
                    best = cur[j]
                    best_end = i
        prev = cur
    if best == 0:
        return 0, ""
    return best, " ".join(a_w[best_end - best : best_end])


def cot_leaks(chain: list, prompt: str, bound_idx: int | None = None) -> tuple[list[dict], int, int]:
    """For each student assistant message with reasoning in this turn's window
    (after the prompt, before bound_idx), detect verbatim copying
    (>= LEAK_WORDS consecutive words) from ANY earlier skill message:
    earlier assistant reasoning_content / visible content, or earlier user
    messages containing a <skill> block. The current turn's own skill block
    is the task and is excluded. Tool results are legitimate to quote and are
    excluded as sources.
    Returns (leaks, leaked_msgs, student_msgs_with_reasoning)."""
    idx = find_prompt_idx(chain, prompt)
    if idx is None:
        return [], 0, 0
    end = bound_idx if bound_idx is not None else len(chain)
    cur_skill_m = re.search(r'<skill name="([^"]+)"', prompt)
    cur_skill = cur_skill_m.group(1) if cur_skill_m else None
    leaks: list[dict] = []
    student_msgs = 0
    leaked_msgs = 0
    prev_sources: list[tuple[str, str, int]] = []  # (label, text, position)
    for i, m in enumerate(chain):
        if not isinstance(m, dict):
            continue
        role = m.get("role")
        if role == "assistant":
            rc = m.get("reasoning_content") or ""
            content = m.get("content")
            content = content if isinstance(content, str) else ""
            in_window = idx < i < end
            if in_window and rc:
                student_msgs += 1
                rc_cmp = strip_paths(rc)
                best = None  # (len, snippet, label, position)
                for label, text, pos in prev_sources:
                    L, snippet = longest_common_word_seq(rc_cmp, text)
                    if best is None or L > best[0]:
                        best = (L, snippet, label, pos)
                if best is not None and best[0] >= LEAK_WORDS:
                    # kind: "earlier" = a prior skill message (the injected
                    # pair, an earlier turn's reply/reasoning, or an earlier
                    # user skill block); "self" = the student's own earlier
                    # reasoning in this same turn.
                    leaks.append(
                        {
                            "msg": i,
                            "source": best[2],
                            "kind": "earlier" if best[3] <= idx else "self",
                            "overlap_words": best[0],
                            "overlapped_text": best[1][:300],
                        }
                    )
                    leaked_msgs += 1
            prev_sources.append((f"assistant@{i} reasoning_content", strip_paths(rc), i))
            if content:
                prev_sources.append((f"assistant@{i} content", strip_paths(content), i))
        elif role == "user":
            t = user_text(m)
            if i != idx and "<skill name=" in t:
                src_skill_m = re.search(r'<skill name="([^"]+)"', t)
                src_skill = src_skill_m.group(1) if src_skill_m else None
                # An earlier block of the SAME skill is the same document as
                # the current task — quoting it is legitimate, not a leak.
                # Earlier blocks of OTHER skills remain leak sources.
                if not (cur_skill and src_skill and src_skill == cur_skill):
                    prev_sources.append((f"user@{i} skill block", strip_paths(t), i))
    return leaks, leaked_msgs, student_msgs


