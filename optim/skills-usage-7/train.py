def norm(s: str | None) -> str:
    s = s or ""
    s = re.sub(r"[*_`]", "", s)
    s = re.sub(r"\s+", " ", s).strip().lower()
    return s.strip(".!? ")


def expected_tool(case: dict) -> tuple[str, dict] | None:
    for step in case["expected"]:
        tcs = step.get("tool_calls")
        if tcs:
            fn = tcs[0]["function"]
            args = fn.get("arguments")
            if isinstance(args, str):
                try:
                    args = json.loads(args)
                except json.JSONDecodeError:
                    pass
            return fn.get("name"), args
    return None


def expected_final(case: dict) -> str | None:
    for step in reversed(case["expected"]):
        c = step.get("content")
        if isinstance(c, str) and c.strip():
            return c
    return None


def bash_tokens(command: str) -> tuple[str, list[str]]:
    import posixpath

    toks = shlex.split(command or "")
    # resolve a leading `cd <dir> && ` prefix (the example doc's canonical
    # form: run from the scripts dir as `./example.sh`)
    if len(toks) >= 4 and toks[0] == "cd" and "&&" in toks:
        sep = toks.index("&&")
        cd_dir = toks[1]
        rest = toks[sep + 1:]
        if rest and rest[0] in ("bash", "sh"):
            rest = rest[1:]
        if rest:
            script = rest[0]
            if not script.startswith("/"):
                script = posixpath.normpath(cd_dir.rstrip("/") + "/" + script)
            return script, rest[1:]
    if toks and toks[0] == "bash" and len(toks) > 1:
        return toks[1], toks[2:]
    if toks:
        return toks[0], toks[1:]
    return "", []


def bash_expected_args(case: dict) -> list[list[str]]:
    """Accepted argument token lists for the example script call."""
    c = case["case"]
    if c == "example-by":
        return [["Bye"]]
    if c == "example-hi":
        return [["Hi"]]
    if c == "example-call-script":
        return [[], ["call", "script"]]
    if c == "example-hello-lower":
        return [["hello"]]
    return [[]]


def tool_match(case: dict, students: list[dict]) -> tuple[float, str]:
    exp = expected_tool(case)
    if exp is None:
        called = [tc for s in students for tc in s["tool_calls"]]
        if not called:
            return 1.0, "no tool expected, none made"
        return 0.5, f"no tool expected but called: {called[:2]}"

    exp_name, exp_args = exp
    all_calls = [(s, tc) for s in students for tc in s["tool_calls"]]

    def matches(tc: dict) -> bool:
        if tc.get("name") != exp_name:
            return False
        args = tc.get("args") or {}
        if exp_name == "read":
            return args.get("path") == exp_args.get("path")
        if exp_name == "bash":
            path, tok = bash_tokens(str(args.get("command", "")))
            if case["case"].startswith("webfetch"):
                # script must be webfetch.sh (the skill doc prints an example
                # path from a sibling repo, so accept any scripts/webfetch.sh)
                # with the exact URL/flag tokens from the gold command
                # (trailing slash on the URL is irrelevant)
                def norm_url(ts: list[str]) -> list[str]:
                    return [t[:-1] if t.startswith("http") and t.endswith("/") else t for t in ts]

                exp_path, exp_tok = bash_tokens(
                    str((exp_args or {}).get("command", ""))
                )
                return (
                    path.endswith("scripts/webfetch.sh")
                    and bool(exp_path)
                    and norm_url(tok) == norm_url(exp_tok)
                )
            if not path.endswith("scripts/example.sh"):
                return False
            return tok in bash_expected_args(case)
        return False

    # first student call must match for full credit
    first = all_calls[0][1] if all_calls else None
    if first is not None and matches(first):
        return 1.0, f"first call matches expected ({exp_name})"
    if any(matches(tc) for _, tc in all_calls):
        return 0.5, f"expected {exp_name} call appears but not first: {[tc.get('name') for _, tc in all_calls[:3]]}"
    return 0.0, f"expected {exp_name} {json.dumps(exp_args)[:120]}; got {[(tc.get('name'), str(tc.get('args'))[:80]) for _, tc in all_calls[:3]]}"


def final_match(case: dict, final: str | None) -> tuple[float, str]:
    exp = expected_final(case)
    if exp is None:
        return 0.0, "no expected final text"
    final = final or ""
    n_exp, n_final = norm(exp), norm(final)
    if n_final == n_exp:
        return 1.0, "exact"
    case_name = case["case"]
    if case_name.startswith("tzip-"):
        if n_exp in n_final and len(n_final) <= 2 * len(n_exp):
            return 0.5, f"extra text around expected line: {final[:120]!r}"
        return 0.0, f"expected {exp!r}, got {final[:160]!r}"
    if case_name == "example-empty":
        if n_exp in n_final:
            return 0.5, f"expected exactly {exp!r}, got {final[:160]!r}"
        return 0.0, f"expected {exp!r}, got {final[:160]!r}"
    if case_name == "example-hello":
        first_line = (final or "").strip().splitlines()[0] if final and final.strip() else ""
        if norm(first_line) == n_exp:
            return 0.5, f"expected exactly {exp!r}, got {final[:160]!r}"
        return 0.0, f"expected {exp!r}, got {final[:160]!r}"
    if case_name.startswith("webfetch"):
        if "tangled group" in n_final:
            return 1.0, "fetched page content reported"
        if "tangledgroup.com" in n_final:
            return 0.5, f"URL mentioned but page content missing: {final[:120]!r}"
        return 0.0, f"expected the fetched page content, got {final[:160]!r}"
    # example script cases: the output must be reported
    # (no trailing period in the needle: norm() strips the period from the
    # end of the whole string, so a final ending with the output line would
    # never match a period-terminated needle)
    if "this is example.sh output" in n_final:
        return 1.0, "script output reported"
    if "example.sh output" in n_final:
        return 0.5, f"partial output report: {final[:160]!r}"
    return 0.0, f"expected script output report, got {final[:160]!r}"


def score_case(case: dict, students: list[dict], final: str | None) -> tuple[float, dict]:
    t_score, t_detail = tool_match(case, students)
    f_score, f_detail = final_match(case, final)
    if expected_tool(case) is not None:
        score = 0.5 * t_score + 0.5 * f_score
    else:
        score = f_score
    return score, {"tool": t_detail, "final": f_detail}


