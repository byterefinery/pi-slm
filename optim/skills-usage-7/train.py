def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sub.add_parser("baseline", help="score the current skill-pair.json")

    po = sub.add_parser("optimize", help="run GEPA optimization (resumable via --run-dir)")
    po.add_argument("--run-dir", default=None)
    po.add_argument("--max-calls", type=int, default=36)
    po.add_argument(
        "--regenerate-thinking",
        action="store_true",
        help="teacher regenerates the seed 'thinking' field before the run",
    )
    po.add_argument("--seed-pair", default=str(PAIR_FILE),
                    help="pair JSON to start from (default: skill-pair.json)")
    po.add_argument("--all-cases", action="store_true",
                    help="optimize on all 12 cases (default: core 4-case subset)")

    pe = sub.add_parser("eval", help="score an arbitrary pair file")
    pe.add_argument("--pair", default=str(PAIR_FILE))

    args = ap.parse_args()

    log(f"### train.py {args.cmd} started (run_id={RUN_ID}, python={sys.version.split()[0]})")

    if args.cmd == "baseline":
        cases = load_cases()
        pair = load_pair()
        res = evaluate_pair(pair, cases, "baseline")
        out = RUNS_DIR / f"baseline-{RUN_ID}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(res, indent=2))
        log(f"results saved to {out}")
    elif args.cmd == "optimize":
        run_gepa(args)
    elif args.cmd == "eval":
        cases = load_cases()
        pair = load_pair(Path(args.pair))
        res = evaluate_pair(pair, cases, f"eval:{Path(args.pair).name}")
        out = RUNS_DIR / f"eval-{Path(args.pair).stem}-{RUN_ID}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(res, indent=2))
        log(f"results saved to {out}")


if __name__ == "__main__":
    main()
